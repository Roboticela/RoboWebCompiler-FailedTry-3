static_assert(sizeof(kFont) / sizeof(kFont[0]) == 95, "ASCII font must cover characters 32 through 126");

const unsigned char* RowsFor(char32_t codePoint) {
    if (codePoint >= 32 && codePoint <= 126) {
        return kFont[codePoint - 32];
    }
    if (codePoint == 0xA0) {
        return kFont[0];
    }
    if (codePoint == 0x2022) {
        return kFont['*' - 32];
    }
    return kFont['?' - 32];
}

void Plot(std::uint8_t* pixels, int frameWidth, int frameHeight, int x, int y, Color color) {
    if (x < 0 || y < 0 || x >= frameWidth || y >= frameHeight) {
        return;
    }
    const std::size_t offset = static_cast<std::size_t>((y * frameWidth + x) * 4);
    pixels[offset] = color.red;
    pixels[offset + 1] = color.green;
    pixels[offset + 2] = color.blue;
    pixels[offset + 3] = color.alpha;
}

