int LineHeightPx(int fontSizePx) {
    if (fontSizePx < 1) {
        fontSizePx = 1;
    }
    return fontSizePx * LINE_HEIGHT_NUMERATOR / LINE_HEIGHT_DENOMINATOR;
}

int CharAdvancePx(int fontSizePx) {
    if (fontSizePx < 2) {
        return 1;
    }
    return fontSizePx / 2;
}

int EmToPx(int fontSizePx, int milli) {
    return (fontSizePx * milli + 500) / 1000;
}

int MeasureTextPx(const std::string& text, int fontSizePx) {
    const int advance = CharAdvancePx(fontSizePx);
    int width = 0;
    std::size_t index = 0;
    while (index < text.size()) {
        char32_t codePoint = 0;
        DecodeUtf8(text, index, codePoint);
        if (codePoint == '\n') {
            continue;
        }
        width += advance;
    }
    return width;
}

void DrawTextPx(
    std::uint8_t* pixels,
    int frameWidth,
    int frameHeight,
    int x,
    int y,
    const std::string& text,
    int fontSizePx,
    Color color,
    bool bold,
    bool italic) {
    const int advance = CharAdvancePx(fontSizePx);
    const int scaleY = fontSizePx >= 14 ? 2 : 1;
    const int scaleX = advance >= 10 ? 2 : 1;
    int cursor = x;
    std::size_t index = 0;
    while (index < text.size()) {
        char32_t codePoint = 0;
        DecodeUtf8(text, index, codePoint);
        if (codePoint == '\n') {
            continue;
        }
        const unsigned char* rows = RowsFor(codePoint);
        for (int row = 0; row < kGlyphHeight; ++row) {
            for (int col = 0; col < kGlyphWidth; ++col) {
                if ((rows[row] & (1 << (kGlyphWidth - 1 - col))) == 0) {
                    continue;
                }
                const int shear = italic ? (kGlyphHeight - row) / 3 : 0;
                for (int sy = 0; sy < scaleY; ++sy) {
                    for (int sx = 0; sx < scaleX; ++sx) {
                        const int px = cursor + shear + col * scaleX + sx;
                        const int py = y + row * scaleY + sy;
                        Plot(pixels, frameWidth, frameHeight, px, py, color);
                        if (bold) {
                            Plot(pixels, frameWidth, frameHeight, px + 1, py, color);
                        }
                    }
                }
            }
        }
        cursor += advance;
    }
}

